#!/usr/bin/env python3
"""baseline.py - the pristine reference state of every adapter (no git needed).

A baseline answers three questions without requiring a repository:

  * what did this adapter look like when it was installed?
  * has the working tree drifted from that state?
  * can the original bytes be handed back on demand?

Storage (all under `.vise/`, a generated artifact - never committed, C7):

    .vise/baseline/<adapter_id>/manifest.json   per-file sha256 + size
    .vise/baseline/<adapter_id>/tree/           full copy of the adapter tree

The tree copy is intentional: a manifest alone records *that* something
changed but not the bytes needed to diff or restore, and adapter trees are
small enough that copying them is cheaper than reconstructing them.

When the baseline is captured
-----------------------------
At install time, from `init/setup.sh`, and **only if absent**. Re-running
setup must never overwrite an existing baseline: if a user has already edited
an adapter, re-baselining would silently bless the edited state as "original".
Accepting a new reference is therefore an explicit act (`rebaseline`).

Providers and the release manifest
----------------------------------
Baselines are produced by a *provider*: a callable returning a fingerprint
plus, optionally, the bytes. Two ship here:

  install   fingerprint the working tree exactly as it sits on disk
            (copy-producing: `tree` is the adapter directory itself)
  release   read `vise.release.json` from the tree root (hash-only:
            `tree` is None - the manifest supplies only hashes)

`vise.release.json` is an ordinary in-tree file generated by
`core/release.py`, so it rides along with any distribution channel (zip,
tarball, rsync, clone). It is *advisory* input to `upgrade`, never a licence
to drop on-disk edits silently. A hash-only provider cannot originate bytes:
`establish` then requires `tree_from=<dir>` and copies only the
fingerprinted files, verifying every hash before accepting them - bytes that
do not match the manifest never become anyone's "original".

Every baseline records its provenance: the provider that produced it, the
release it describes (when known), and whether it is *vendor-sourced*. A
baseline refreshed from a user-edited tree (`rebaseline --force`) is not
vendor-sourced and can no longer serve as the old side of an upgrade
three-way compare.

Upgrades
--------
`init/setup.sh` stamps `.vise/version` with `core/version.py:VERSION`. A
later setup run that sees a different stamp reconciles baselines against the
release manifest shipped in the tree, deciding **per file** from three
inputs - the old baseline (O), the new release manifest (N) and the disk
scan (D); presence in each is a first-class state (`classify`):

  vendor changed/added/removed, disk untouched  -> apply (update/delete)
  vendor unchanged, disk drifted                -> keep (the drift stays drift)
  disk already matches the release              -> keep
  all three differ / deletion with drift        -> review (never touched)
  on disk but in neither manifest               -> user file (never touched)

The refresh is partial: decided files are applied and the new baseline is
assembled file by file (release bytes for vendor files, the old entry held
back where new bytes are unavailable); only review paths are reported. A
review path means "Vise cannot attribute the change" - not "you edited
this". The safe flow passes the new release as a staged tree
(`upgrade --staged DIR`, driven by `init/setup.sh --upgrade-from DIR`) so
the compare runs *before* any overwrite; reconciling after a raw
extract-over cannot recover pre-extraction edits (those are only reachable
through C13 snapshots). A tree without a release manifest (pre-manifest
releases) falls back to whole-adapter verdicts: clean adapters re-stamp,
modified ones are reported for review - never auto-accepted.

Exit codes (agent-friendly, baseline domain - distinct from the `viseinit`
0-6 map):
  establish/path/version  0 ok, 2 usage or input error
  status                  0 every adapter is clean, 1 modified/unbaselined
  diff                    0 no drift, 1 drift detected, 2 usage
  verify                  0 intact, 1 corrupted tree / no adapters, 2 usage
  upgrade                 0 fully reconciled, 1 review items remain,
                          2 usage or input error (bad staged tree, downgrade,
                          unreadable release manifest)
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import shutil
import sys
import time
from pathlib import Path
from typing import Callable

from version import VERSION as VISE_VERSION

VISE_ROOT = Path(__file__).resolve().parent.parent
REGISTRY_PATH = VISE_ROOT / ".vise" / "registry.json"
BASELINE_DIR = VISE_ROOT / ".vise" / "baseline"
VERSION_FILE = VISE_ROOT / ".vise" / "version"
RELEASE_MANIFEST = "vise.release.json"
# 2 adds the provenance fields (release / vendor_sourced / held_back). Readers
# tolerate their absence: a missing vendor_sourced predates the field and is
# treated as True (install-time scans were vendor references by definition).
BASELINE_VERSION = 2

# Runtime noise, not adapter source: excluded from both the fingerprint and
# the copied tree (a `.bak` from file_patch must not drift the baseline).
IGNORE_DIRS = {"__pycache__", ".git", ".vise"}
IGNORE_SUFFIXES = (".pyc", ".pyo", ".bak", ".swp", ".orig", ".rej")
IGNORE_NAMES = {".DS_Store", "Thumbs.db"}


def _utcnow() -> str:
    return time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())


def sha256_of(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(65536), b""):
            h.update(chunk)
    return h.hexdigest()


def is_ignored(rel: Path) -> bool:
    if any(part in IGNORE_DIRS for part in rel.parts):
        return True
    if rel.name in IGNORE_NAMES or rel.name.endswith(IGNORE_SUFFIXES):
        return True
    return False


def iter_files(root: Path) -> list[tuple[Path, Path]]:
    """(relative, absolute) for every source file under root, sorted."""
    out = []
    for path in sorted(root.rglob("*")):
        if not path.is_file():
            continue
        rel = path.relative_to(root)
        if is_ignored(rel):
            continue
        out.append((rel, path))
    return out


def scan(root: Path) -> dict[str, dict]:
    """Fingerprint a tree: relative path -> {sha256, size}."""
    files: dict[str, dict] = {}
    for rel, path in iter_files(root):
        files[str(rel)] = {"sha256": sha256_of(path), "size": path.stat().st_size}
    return files


def tree_sha(files: dict[str, dict]) -> str:
    """One hash summarizing a whole fingerprint (order-independent)."""
    h = hashlib.sha256()
    for rel in sorted(files):
        h.update(f"{rel}\0{files[rel]['sha256']}\n".encode("utf-8"))
    return h.hexdigest()


# --- providers ---------------------------------------------------------------
# Contract: given an adapter directory, return
#   {"files":   {rel: {"sha256", "size"}},   # the fingerprint of record
#    "tree":    Path | None,                 # bytes to copy into tree/
#    "release": str | None}                  # release the fingerprint describes
# A provider with tree=None is hash-only: it can verify a tree against its
# hashes but cannot originate bytes, so establish() requires an explicit
# `tree_from=<dir>` for it and copies only the fingerprinted files, verifying
# each hash first. That verify shape is what keeps a release manifest
# advisory-but-safe: bytes that do not match the manifest are never labelled
# "original".

def release_manifest_path(root: Path) -> Path:
    return root / RELEASE_MANIFEST


def load_release_manifest(root: Path) -> dict | None:
    """The release manifest shipped inside a tree, or None (pre-manifest tree).

    Raises ValueError when the file exists but is unreadable or misshapen:
    a corrupt manifest is a loud input error, not an absent one.
    """
    path = release_manifest_path(root)
    if not path.is_file():
        return None
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, OSError) as exc:
        raise ValueError(f"{RELEASE_MANIFEST} unreadable: {exc}")
    if not isinstance(data, dict) or not isinstance(data.get("adapters"), dict):
        raise ValueError(f"{RELEASE_MANIFEST} has an unexpected shape "
                         "(expected an object with an 'adapters' map)")
    return data


def _adapter_id_for(dir_path: Path) -> str | None:
    try:
        data = json.loads((dir_path / "vise.adapter.json")
                          .read_text(encoding="utf-8"))
    except (json.JSONDecodeError, OSError):
        return None
    return data.get("adapter_id") if isinstance(data, dict) else None


def _provider_install_scan(dir_path: Path) -> dict:
    return {"files": scan(dir_path), "tree": dir_path, "release": None}


def _provider_release_manifest(dir_path: Path) -> dict:
    # The manifest rides with its tree: <root>/vise.release.json sits next to
    # <root>/adapters/, so the adapter dir locates it for any tree root.
    root = dir_path.parent.parent
    data = load_release_manifest(root)
    if data is None:
        raise ValueError(f"no {RELEASE_MANIFEST} in {root} - "
                         "not a release tree")
    aid = _adapter_id_for(dir_path)
    entry = (data["adapters"].get(aid) or {}) if aid else {}
    if not entry.get("files"):
        raise ValueError(f"{RELEASE_MANIFEST} does not cover adapter "
                         f"'{aid or dir_path.name}'")
    return {"files": entry["files"], "tree": None,
            "release": data.get("release")}


PROVIDERS: dict[str, Callable[[Path], dict]] = {
    "install": _provider_install_scan,
    "release": _provider_release_manifest,
}


def _copy_patterns() -> list[str]:
    return (list(IGNORE_DIRS) + [f"*{s}" for s in IGNORE_SUFFIXES]
            + list(IGNORE_NAMES))


# --- registry / path helpers -------------------------------------------------

def registry_adapters() -> list[dict]:
    """Enabled adapters from the generated registry; [] plus a hint if unusable."""
    if not REGISTRY_PATH.is_file():
        print(f"baseline: {REGISTRY_PATH.relative_to(VISE_ROOT)} not found "
              "(generated artifact). Run: bash init/setup.sh", file=sys.stderr)
        return []
    try:
        data = json.loads(REGISTRY_PATH.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, OSError) as exc:
        print(f"baseline: registry unreadable ({exc}). "
              "Regenerate it with: bash init/setup.sh", file=sys.stderr)
        return []
    if not isinstance(data, dict):
        print("baseline: registry has an unexpected shape. "
              "Regenerate it with: bash init/setup.sh", file=sys.stderr)
        return []
    return [a for a in data.get("adapters", [])
            if a.get("enabled") and a.get("path")]


def adapter_dir(adapter_id: str) -> Path | None:
    for a in registry_adapters():
        if a["adapter_id"] == adapter_id:
            return (VISE_ROOT / a["path"]).resolve()
    return None


def orphan_ids() -> dict[str, list[str]]:
    """Generated state whose adapter is no longer in the registry.

    Returns {"baseline": [...], "snapshots": [...], "patches": [...]} (only
    non-empty kinds). Removing an adapter from `adapters/` leaves this residue
    behind; it is reported (doctor) and cleaned explicitly (`visectl clean
    --state`), never auto-deleted - an orphan's baseline tree is the last
    surviving copy of that adapter's original bytes, and its patches may hold
    unpublished improvements.
    """
    known = {a["adapter_id"] for a in registry_adapters()}
    out: dict[str, list[str]] = {}
    for name, root in (("baseline", BASELINE_DIR),
                       ("snapshots", VISE_ROOT / ".vise" / "snapshots"),
                       ("patches", VISE_ROOT / ".vise" / "patches")):
        if not root.is_dir():
            continue
        orphans = sorted(d.name for d in root.iterdir()
                         if d.is_dir() and d.name not in known)
        if orphans:
            out[name] = orphans
    return out


def stamped_version() -> str | None:
    """The Vise version this install was last set up with, or None."""
    try:
        return VERSION_FILE.read_text(encoding="utf-8").strip() or None
    except OSError:
        return None


def manifest_path(adapter_id: str) -> Path:
    return BASELINE_DIR / adapter_id / "manifest.json"


def tree_dir(adapter_id: str) -> Path:
    return BASELINE_DIR / adapter_id / "tree"


def load(adapter_id: str) -> dict | None:
    """Read a baseline manifest, or None when the adapter is unbaselined.

    A manifest whose tree copy is gone counts as *absent*, not as a usable
    baseline: `.vise/baseline/` holds generated state, and a half-deleted
    baseline (partial cleanup, interrupted write) would otherwise be reported
    as `clean` while `restore` fails. Treating it as absent is self-healing -
    the next `establish` recreates it.
    """
    path = manifest_path(adapter_id)
    if not path.is_file():
        return None
    if not tree_dir(adapter_id).is_dir():
        print(f"baseline: {adapter_id} has no tree copy (incomplete baseline); "
              "run: bash init/setup.sh", file=sys.stderr)
        return None
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, OSError) as exc:
        print(f"baseline: {adapter_id} manifest unreadable ({exc})",
              file=sys.stderr)
        return None


# --- core operations ---------------------------------------------------------

def _write_baseline(adapter_id: str, files: dict, sources: dict[str, Path],
                    *, provider: str, release: str | None,
                    vendor_sourced: bool, vise_version: str,
                    source_root: str | None,
                    held_back: list[str] | None = None) -> dict:
    """Assemble tree/ from `sources` (relpath -> file to copy) + write manifest.

    The new tree is built beside its destination and swapped in, and the old
    tree is removed only after the swap succeeds: an interrupt leaves either
    the old or the new baseline intact, never a half-written one.
    """
    dest = tree_dir(adapter_id)
    dest.parent.mkdir(parents=True, exist_ok=True)
    build = dest.parent / f".building-{adapter_id}"
    trash = dest.parent / f".trash-{adapter_id}"
    for p in (build, trash):
        if p.exists():
            shutil.rmtree(p)
    build.mkdir()
    swapped = False
    try:
        for rel in sorted(files):
            src = sources.get(rel)
            if src is None or not src.is_file():
                raise ValueError(f"{adapter_id}: no source bytes for '{rel}'")
            target = build / rel
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(src, target)
        if dest.exists():
            os.rename(dest, trash)
        os.rename(build, dest)
        swapped = True
    except Exception:
        shutil.rmtree(build, ignore_errors=True)
        if not swapped and not dest.exists() and trash.exists():
            os.rename(trash, dest)  # put the old baseline back
        raise
    shutil.rmtree(trash, ignore_errors=True)

    manifest = {
        "version": BASELINE_VERSION,
        "adapter_id": adapter_id,
        "provider": provider,
        "release": release,
        "vendor_sourced": vendor_sourced,
        "established_at": _utcnow(),
        "vise_version": vise_version,
        "source_root": source_root,
        "files": files,
    }
    if held_back:
        manifest["held_back"] = sorted(held_back)
    path = manifest_path(adapter_id)
    tmp = path.with_suffix(".json.tmp")
    tmp.write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n",
                   encoding="utf-8")
    os.replace(tmp, path)  # atomic on POSIX and Windows
    return manifest


def establish(adapter_id: str, provider: str = "install",
              refresh: bool = False,
              tree_from: Path | None = None) -> dict:
    """Create the baseline; skip when one exists unless `refresh` is set."""
    src = adapter_dir(adapter_id)
    if src is None:
        return {"adapter_id": adapter_id, "status": "unknown-adapter"}
    existing = load(adapter_id)
    if existing is not None and not refresh:
        return {"adapter_id": adapter_id, "status": "kept",
                "established_at": existing.get("established_at"),
                "files": len(existing.get("files", {}))}
    prov = PROVIDERS.get(provider)
    if prov is None:
        raise ValueError(f"unknown baseline provider: {provider}")
    result = prov(src)
    files = result["files"]
    byte_src = result.get("tree")
    if byte_src is None:
        # Hash-only provider: bytes must come from an explicit tree, and each
        # fingerprinted file is verified before any byte is accepted as
        # "original" - a staged tree that disagrees with its own manifest is
        # corruption, not a baseline.
        if tree_from is None:
            raise ValueError(f"provider '{provider}' is hash-only; pass "
                             "tree_from=<dir holding the bytes>")
        byte_src = Path(tree_from)
        bad = [rel for rel, meta in files.items()
               if not (byte_src / rel).is_file()
               or sha256_of(byte_src / rel) != meta["sha256"]]
        if bad:
            raise ValueError(
                f"{byte_src} does not match the provider's fingerprint: "
                f"{len(bad)} file(s) differ, e.g. {bad[0]}")
    sources = {rel: byte_src / rel for rel in files}

    if provider == "install":
        if existing is None:
            vendor_sourced = True   # the install-time tree IS the reference
        elif drift(adapter_id)["clean"]:
            # Bytes unchanged - carry the previous provenance over.
            vendor_sourced = existing.get("vendor_sourced", True)
        else:
            vendor_sourced = False  # accepting a user-edited tree (rebaseline)
    else:
        vendor_sourced = True       # hashes verified above

    manifest = _write_baseline(
        adapter_id, files, sources,
        provider=provider, release=result.get("release"),
        vendor_sourced=vendor_sourced, vise_version=VISE_VERSION,
        source_root=str(src.relative_to(VISE_ROOT)))
    return {"adapter_id": adapter_id,
            "status": "refreshed" if existing else "created",
            "established_at": manifest["established_at"],
            "files": len(manifest["files"])}


def drift(adapter_id: str) -> dict:
    """File-level drift of the working tree against its baseline."""
    src = adapter_dir(adapter_id)
    if src is None:
        return {"adapter_id": adapter_id, "baselined": False,
                "reason": "unknown adapter"}
    base = load(adapter_id)
    if base is None:
        return {"adapter_id": adapter_id, "baselined": False,
                "reason": "no baseline"}
    old = base.get("files", {})
    cur = scan(src)
    changed = sorted(p for p in old.keys() & cur.keys()
                     if old[p]["sha256"] != cur[p]["sha256"])
    added = sorted(cur.keys() - old.keys())
    removed = sorted(old.keys() - cur.keys())
    return {"adapter_id": adapter_id, "baselined": True,
            "clean": not (changed or added or removed),
            "changed": changed, "added": added, "removed": removed,
            "established_at": base.get("established_at"),
            "tree_sha": tree_sha(cur)}


def state(adapter_id: str) -> str:
    """'clean' | 'modified' | 'unbaselined'."""
    d = drift(adapter_id)
    if not d["baselined"]:
        return "unbaselined"
    return "clean" if d["clean"] else "modified"


def verify(adapter_id: str) -> dict:
    """Check the baseline tree copy still matches its manifest, byte for byte.

    The manifest is the truth about *hashes*; the tree is the truth about
    *bytes*. Drift detection trusts the manifest, and `restore --base` trusts
    the tree - so a tampered or half-written tree would silently make restore
    produce files that no longer match the manifest. This check turns that
    silent corruption into a loud, actionable failure.
    """
    if adapter_dir(adapter_id) is None:
        return {"adapter_id": adapter_id, "status": "unknown-adapter",
                "ok": False}
    base = load(adapter_id)
    if base is None:
        # Nothing to verify is not corruption: the adapter keeps working.
        return {"adapter_id": adapter_id, "status": "unbaselined", "ok": True}
    expected = base.get("files", {})
    actual = {str(rel): sha256_of(path)
              for rel, path in iter_files(tree_dir(adapter_id))}
    changed = sorted(p for p in expected.keys() & actual.keys()
                     if expected[p]["sha256"] != actual[p])
    missing = sorted(expected.keys() - actual.keys())
    added = sorted(actual.keys() - expected.keys())
    corrupted = bool(changed or missing or added)
    return {"adapter_id": adapter_id,
            "status": "corrupted" if corrupted else "ok",
            "ok": not corrupted,
            "changed": changed, "missing": missing, "added": added,
            "established_at": base.get("established_at")}


# --- upgrade reconcile (three-way, per file) ---------------------------------

def _version_key(v: str) -> tuple[int, ...] | None:
    try:
        return tuple(int(x) for x in str(v).split("."))
    except (ValueError, AttributeError):
        return None


def version_compare(a: str, b: str) -> int | None:
    """-1/0/1 like cmp, or None when either side is not dotted numbers."""
    ka, kb = _version_key(a), _version_key(b)
    if ka is None or kb is None:
        return None
    return (ka > kb) - (ka < kb)


def classify(old: dict, new: dict, disk: dict) -> dict[str, str]:
    """Per-file upgrade decision from three presences (see module docstring).

    `old`, `new` and `disk` map relpath -> {"sha256", ...}; absence from a
    mapping is a first-class state (vendor deletion, vendor addition, user
    file), not just a hash inequality. Returns {relpath: action} with action
    in keep | update | delete | review | user.
    """
    out: dict[str, str] = {}
    for path in sorted(old.keys() | new.keys() | disk.keys()):
        o, n, d = old.get(path), new.get(path), disk.get(path)
        oh = o["sha256"] if o else None
        nh = n["sha256"] if n else None
        dh = d["sha256"] if d else None
        if o is None and n is None:
            out[path] = "user"             # in neither manifest: never touch
        elif n is not None and dh == nh:
            out[path] = "keep"             # disk already at the release bytes
        elif n is None:
            out[path] = ("keep" if d is None            # deletion already gone
                         else "delete" if dh == oh      # vendor dropped it
                         else "review")                 # ...but disk drifted
        elif d is None:
            out[path] = "update"           # vendor bytes missing on disk
        elif o is None:
            out[path] = "review"           # disk file collides with an addition
        elif dh == oh:
            # vendor moved (or not), disk untouched since the old baseline
            out[path] = "keep" if nh == oh else "update"
        elif nh == oh:
            out[path] = "keep"             # local drift, vendor unchanged
        else:
            out[path] = "review"           # all three differ: unknown origin
    return out


def _review_reason(path: str, old: dict, new: dict) -> str:
    """Why a path landed in review - attribution unknown, never an accusation."""
    if path not in new:
        return ("the release drops this file, but the on-disk copy differs "
                "from the old baseline - left in place; delete it yourself "
                "if unwanted")
    if path not in old:
        return ("the release adds this path, but a different file already "
                "exists there - left in place; the release copy was not "
                "written")
    return ("matches neither the old baseline nor the new release manifest - "
            "Vise cannot attribute the change (a local edit, a skipped "
            "release, or an interrupted earlier upgrade); left in place")


def _legacy_upgrade() -> list[dict]:
    """Whole-adapter reconcile for a tree with no usable release manifest.

    Kept for installs upgrading *from* a release that predates manifests:
    without a vendor-supplied hash list there is no third leg to compare, so
    the verdicts stay per-adapter (clean re-stamp, modified needs review).
    """
    rows = []
    for a in registry_adapters():
        aid = a["adapter_id"]
        d = drift(aid)
        if not d["baselined"]:
            r = establish(aid)
            rows.append({"adapter_id": aid, "action": "baselined",
                         "files": r.get("files", 0)})
        elif d["clean"]:
            r = establish(aid, refresh=True)
            rows.append({"adapter_id": aid, "action": "refreshed",
                         "files": r.get("files", 0)})
        else:
            rows.append({"adapter_id": aid, "action": "needs-review",
                         "changed": len(d["changed"]), "added": len(d["added"]),
                         "removed": len(d["removed"])})
    return rows


def _verify_staged(root: Path, man_adapters: dict) -> None:
    """Refuse a staged tree that disagrees with its own release manifest."""
    problems = []
    for aid, entry in sorted(man_adapters.items()):
        adir = root / entry.get("path", "")
        want = {rel: meta["sha256"] for rel, meta
                in entry.get("files", {}).items()}
        got = ({rel: meta["sha256"] for rel, meta in scan(adir).items()}
               if adir.is_dir() else {})
        if got != want:
            only_manifest = sorted(want.keys() - got.keys())
            only_tree = sorted(got.keys() - want.keys())
            changed = sorted(p for p in want.keys() & got.keys()
                             if want[p] != got[p])
            problems.append(
                f"{aid}: {len(changed)} changed, {len(only_manifest)} "
                f"missing, {len(only_tree)} unlisted")
    if problems:
        raise ValueError(
            "the staged tree does not match its release manifest "
            f"({'; '.join(problems[:3])}{' ...' if len(problems) > 3 else ''}) "
            "- corrupt or tampered input, not a baseline source")


def upgrade(staged: Path | None = None, dry_run: bool = False) -> list[dict]:
    """Reconcile adapters against the release manifest after an upgrade.

    With `staged` pointing at an extracted-but-not-yet-applied release tree,
    the three-way compare runs against the *current* disk - before any
    overwrite - and the staged bytes feed both the apply step and the new
    baselines. Without it, the release is assumed already extracted over
    the install: a file the extract destroyed is still recoverable while
    the vendor has not changed it (the old baseline tree supplies its
    bytes); everything else reconciles per file from what the extract left
    behind, and undecidable paths become review.

    Hard input errors (corrupt staged tree, downgrade, unreadable manifest)
    raise ValueError; per-file undecidables are reported as review rows.
    """
    new_root = Path(staged).resolve() if staged else VISE_ROOT
    rel = load_release_manifest(new_root)
    if rel is None:
        return _legacy_upgrade()
    r_new = rel.get("release") or ""
    stamped = stamped_version()
    if stamped and r_new:
        direction = version_compare(r_new, stamped)
        if direction is not None and direction < 0:
            raise ValueError(
                f"the {'staged ' if staged else ''}release manifest describes "
                f"v{r_new}, but this install is at v{stamped} - refusing a "
                "downgrade; reconcile manually if that is really intended")
    if not staged and r_new and r_new != VISE_VERSION:
        # The manifest and the code disagree about what this tree is: one was
        # bumped without the other. Hash decisions would rest on a stale
        # manifest, so degrade to whole-adapter verdicts.
        print(f"baseline: {RELEASE_MANIFEST} describes v{r_new} but the tree "
              f"is v{VISE_VERSION} - regenerate it with `core/release.py "
              "generate`; falling back to whole-adapter reconcile",
              file=sys.stderr)
        return _legacy_upgrade()
    target_ver = r_new or VISE_VERSION
    man_adapters: dict = rel["adapters"]
    if staged:
        _verify_staged(new_root, man_adapters)

    registered = {a["adapter_id"]: a for a in registry_adapters()}
    rows: list[dict] = []
    for aid in sorted(registered.keys() | man_adapters.keys()):
        a_reg = registered.get(aid)
        a_man = man_adapters.get(aid)
        if a_man is None:
            # Absent from the release: the vendor no longer ships it. Never
            # auto-delete - the directory may hold user files; removing it
            # from adapters/ is the user's act, and the state left behind is
            # then handled by the orphan machinery (doctor / clean --state).
            rows.append({"adapter_id": aid, "action": "review", "reason":
                         f"not covered by the v{r_new} release manifest - the "
                         "release no longer ships this adapter; its files "
                         "were left in place",
                         "updated": 0, "deleted": 0, "kept": 0, "user": 0,
                         "review_files": [], "held_back": []})
            continue
        dst_dir = (VISE_ROOT / (a_reg or a_man)["path"]).resolve()
        new_dir = (new_root / a_man["path"]).resolve()
        base = load(aid)
        if base is not None and not base.get("vendor_sourced", True):
            # The old side of the compare must be vendor bytes; a rebaselined
            # baseline is a user-accepted tree and cannot serve.
            rows.append({"adapter_id": aid, "action": "review", "reason":
                         "its baseline was accepted from an edited tree "
                         "(rebaseline) and is not vendor-sourced - no "
                         "trustworthy old reference to reconcile against; "
                         "re-establish one from pristine release bytes first",
                         "updated": 0, "deleted": 0, "kept": 0, "user": 0,
                         "review_files": [], "held_back": []})
            continue
        old_files = (base or {}).get("files", {})
        new_files = a_man.get("files", {})
        disk_files = scan(dst_dir) if dst_dir.is_dir() else {}
        plan = classify(old_files, new_files, disk_files)

        # Fold the plan into (a) disk actions and (b) the new baseline.
        # Without a staged tree there are no new bytes on hand, so an
        # "update" the disk does not already carry degrades to a review whose
        # baseline entry is held back at the old vendor bytes.
        base_files: dict = {}
        sources: dict[str, Path] = {}
        review_files: list[dict] = []
        held_back: list[str] = []
        updates: list[tuple[str, Path]] = []  # (path, byte source) to copy
        deletes: list[str] = []   # paths to unlink
        counts = {"update": 0, "delete": 0, "keep": 0, "user": 0}
        for path, act in plan.items():
            n = new_files.get(path)
            reason = None
            if act == "update" and not staged:
                # Without a staged tree, "new" bytes must come from what this
                # tree already holds: the disk (already at the release bytes)
                # or the old baseline tree (file unchanged since capture).
                # Anything else is undecidable, not appliable.
                if disk_files.get(path, {}).get("sha256") \
                        == (n or {}).get("sha256"):
                    pass
                elif old_files.get(path, {}).get("sha256") \
                        == (n or {}).get("sha256"):
                    pass
                else:
                    act = "review"
                    reason = ("the release updates this file, but neither the "
                              "on-disk copy nor the old baseline can supply "
                              "the new bytes and no staged tree was given - "
                              "left in place")
            if act == "user":
                counts["user"] += 1
                continue
            if act == "keep":
                if n is None:
                    # classify's "deletion already gone": absent from the
                    # release and from disk alike - realize it as a delete
                    # and keep the path out of the new baseline (there are
                    # no bytes to record and no source to copy from)
                    counts["delete"] += 1
                    deletes.append(path)      # unlink is a guarded no-op
                    continue
                counts["keep"] += 1
                base_files[path] = n
                if staged:
                    sources[path] = new_dir / path
                elif disk_files.get(path, {}).get("sha256") == n.get("sha256"):
                    sources[path] = dst_dir / path
                else:
                    # local drift on a vendor-unchanged file (classify: nh ==
                    # oh): the baseline must record vendor bytes, and only the
                    # old baseline tree holds them - the disk bytes ARE the
                    # drift and must never become the reference (C13)
                    sources[path] = tree_dir(aid) / path
            elif act == "update":
                counts["update"] += 1
                base_files[path] = n
                if staged:
                    updates.append((path, new_dir / path))
                    sources[path] = new_dir / path
                elif disk_files.get(path, {}).get("sha256") == n.get("sha256"):
                    sources[path] = dst_dir / path   # already in place
                else:
                    # vendor bytes missing on disk but the file is unchanged
                    # since the old baseline: restore from the baseline tree
                    updates.append((path, tree_dir(aid) / path))
                    sources[path] = tree_dir(aid) / path
            elif act == "delete":
                counts["delete"] += 1
                deletes.append(path)          # excluded from the new baseline
            else:  # review
                review_files.append({"path": path, "reason":
                                     reason or _review_reason(path, old_files,
                                                              new_files)})
                if n is None:
                    continue                  # vendor deletion, drifted
                if staged:
                    base_files[path] = n      # new bytes on record; the
                    sources[path] = new_dir / path  # on-disk copy stays drift
                elif path in old_files:
                    base_files[path] = old_files[path]
                    sources[path] = tree_dir(aid) / path
                    held_back.append(path)
                # else: addition collision - nothing trustworthy to record,
                # so the path stays out of the baseline (shows as added drift)

        if not dry_run:
            for path, src in updates:
                target = dst_dir / path
                target.parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(src, target)
            for path in deletes:
                victim = dst_dir / path
                if victim.is_file():
                    victim.unlink()

        if a_reg is None:
            action = "added"
        elif base is None:
            action = "baselined"
        elif review_files:
            action = "review"
        elif updates or deletes:
            action = "refreshed"
        else:
            action = "kept"
        stamps_differ = (base is not None and (
            base.get("vise_version") != target_ver
            or base.get("release") != r_new
            or base.get("provider") != "release"))
        if action != "kept" or base is None or stamps_differ:
            if not dry_run:
                _write_baseline(
                    aid, base_files, sources, provider="release",
                    release=r_new or None, vendor_sourced=True,
                    vise_version=target_ver,
                    source_root=a_man.get("path"),
                    held_back=held_back)
        rows.append({"adapter_id": aid, "action": action,
                     "updated": counts["update"], "deleted": counts["delete"],
                     "kept": counts["keep"], "user": counts["user"],
                     "review_files": review_files, "held_back": held_back,
                     "release": r_new})
    return rows


