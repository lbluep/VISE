#!/usr/bin/env python3
"""manifest.py - ledger of artifacts Vise places OUTSIDE VISE_ROOT.

Ledger file: <VISE_ROOT>/.vise/installed.json

Anything Vise writes outside its own tree must be recorded here at write
time (idempotent upsert keyed on (kind, path)). The ledger powers:

  visectl manifest list|verify    - query anytime ("what did Vise add?")
  init/uninstall.sh               - `uninstall-apply` removes/reverts everything

Entry kinds
  created  - a file Vise created outside VISE_ROOT (e.g. ~/.local/bin/congit).
             Records the sha256 captured at install time. Uninstall deletes
             the file only if the checksum still matches; a changed file is
             SKIPPED and reported for manual inspection (user policy: never
             silently delete a file the user may have customized).
  modified - a user file Vise appended to (e.g. the rc marker block).
             Records a revert recipe. Currently the only method is
             remove_marker_block (begin/end markers), which is idempotent.

Wrapper convention (required for the uninstall fallback scan to recognize
Vise-installed commands even when the ledger is lost): every wrapper written
outside VISE_ROOT must contain BOTH a reference to the VISE_ROOT path AND the
header line "# Auto-generated by <source> - do not edit."

Exit codes (agent-friendly):
  add/remove/list/path    0 ok, 2 usage or input error
  verify                  0 all clean, 1 drift detected
  uninstall-apply         0 nothing skipped, 3 drift-skipped files remain
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import sys
import time
from pathlib import Path

VISE_ROOT = Path(__file__).resolve().parent.parent
LEDGER_PATH = VISE_ROOT / ".vise" / "installed.json"
LEDGER_VERSION = 1
MAX_FALLBACK_SCAN_BYTES = 64 * 1024  # wrappers are tiny; skip anything bigger
AUTOGEN_MARK = "Auto-generated by"


def _utcnow() -> str:
    return time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())


def _abspath(p: str) -> str:
    return os.path.abspath(os.path.expanduser(p))


def _read_text(path: Path) -> str:
    return path.read_text(encoding="utf-8", errors="ignore")


def load_ledger() -> dict:
    if not LEDGER_PATH.is_file():
        return {"version": LEDGER_VERSION, "entries": []}
    try:
        data = json.loads(LEDGER_PATH.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, OSError) as exc:
        print(f"manifest: ledger unreadable ({exc}); treating as empty",
              file=sys.stderr)
        return {"version": LEDGER_VERSION, "entries": []}
    if not isinstance(data.get("entries"), list):
        data["entries"] = []
    data["version"] = LEDGER_VERSION
    return data


def save_ledger(data: dict) -> None:
    data["updated_at"] = _utcnow()
    LEDGER_PATH.parent.mkdir(parents=True, exist_ok=True)
    tmp = LEDGER_PATH.with_suffix(".json.tmp")
    tmp.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n",
                   encoding="utf-8")
    os.replace(tmp, LEDGER_PATH)  # atomic on POSIX and Windows


def sha256_of(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(65536), b""):
            h.update(chunk)
    return h.hexdigest()


def strip_marker_block(path: Path, begin: str, end: str) -> bool:
    """Remove the begin..end block (inclusive). Returns True if changed."""
    text = _read_text(path)
    pattern = re.compile(r"(?m)^" + re.escape(begin) + r".*?"
                         + re.escape(end) + r"\n?", re.DOTALL)
    new_text, n = pattern.subn("", text)
    if n == 0:
        return False
    path.write_text(new_text, encoding="utf-8", errors="surrogateescape")
    return True


def cmd_add(args: argparse.Namespace) -> int:
    path = Path(_abspath(args.path))
    data = load_ledger()
    entry = {"kind": args.kind, "path": str(path), "source": args.source,
             "recorded_at": _utcnow()}
    if args.kind == "created":
        if not path.is_file():
            print(f"manifest: created entry requires an existing file: {path}",
                  file=sys.stderr)
            return 2
        entry["sha256"] = args.sha256 or sha256_of(path)
    else:  # modified
        if not args.begin or not args.end:
            print("manifest: modified entry requires --begin/--end markers",
                  file=sys.stderr)
            return 2
        entry["revert"] = {"method": "remove_marker_block",
                           "begin": args.begin, "end": args.end}
    # Upsert keyed on (kind, path)
    data["entries"] = [e for e in data["entries"]
                       if not (e.get("kind") == args.kind
                               and e.get("path") == str(path))]
    data["entries"].append(entry)
    save_ledger(data)
    if args.json:
        print(json.dumps(entry, indent=2))
    else:
        print(f"manifest: recorded {args.kind} {path} (source: {args.source})")
    return 0


def cmd_remove(args: argparse.Namespace) -> int:
    data = load_ledger()
    path = _abspath(args.path)
    before = len(data["entries"])
    data["entries"] = [e for e in data["entries"]
                       if not (e.get("path") == path
                               and (args.kind is None
                                    or e.get("kind") == args.kind))]
    removed = before - len(data["entries"])
    if removed:
        save_ledger(data)
    if args.json:
        print(json.dumps({"path": path, "removed": removed}, indent=2))
    else:
        print(f"manifest: removed {removed} entr"
              f"{'y' if removed == 1 else 'ies'} for {path}")
    return 0


def cmd_list(args: argparse.Namespace) -> int:
    data = load_ledger()
    if args.json:
        print(json.dumps(data, indent=2))
        return 0
    entries = data["entries"]
    if not entries:
        print("manifest: ledger empty (nothing recorded outside VISE_ROOT)")
        return 0
    print(f"{'kind':<10} {'path':<52} source")
    print("-" * 100)
    for e in entries:
        print(f"{e.get('kind', '?'):<10} {e.get('path', '?'):<52} "
              f"{e.get('source', '?')}")
    print(f"\n{len(entries)} entries in {LEDGER_PATH}")
    return 0


def cmd_verify(args: argparse.Namespace) -> int:
    """Check every entry. Exit 0 clean, 1 drift (created file changed)."""
    data = load_ledger()
    results = []
    for e in data["entries"]:
        path = Path(e["path"])
        r = {"kind": e.get("kind"), "path": e["path"], "status": "ok",
             "note": ""}
        if e.get("kind") == "created":
            if not path.exists():
                r["status"], r["note"] = "missing", "file already gone"
            elif not e.get("sha256"):
                r["status"], r["note"] = "drift", "no checksum recorded"
            elif sha256_of(path) != e["sha256"]:
                r["status"], r["note"] = "drift", "content changed since install"
        else:  # modified
            if not path.exists():
                r["note"] = "file gone (nothing to revert)"
            else:
                begin = e.get("revert", {}).get("begin", "")
                if begin and begin not in _read_text(path):
                    r["note"] = "marker absent (already reverted)"
        results.append(r)
    drift = sum(r["status"] == "drift" for r in results)
    summary = {"total": len(results), "ok": len(results) - drift,
               "drift": drift, "ledger": str(LEDGER_PATH)}
    if args.json:
        print(json.dumps({"results": results, "summary": summary}, indent=2))
    else:
        for r in results:
            mark = {"ok": "[OK]  ", "missing": "[GONE]", "drift": "[DRIFT]"}
            line = f"{mark[r['status']]} {r['kind']:<8} {r['path']}"
            if r["note"]:
                line += f"  ({r['note']})"
            print(line)
        if not results:
            print("manifest: ledger empty - nothing to verify")
        else:
            print(f"\nVerify: {summary['ok']}/{summary['total']} clean, "
                  f"{drift} drifted")
    return 1 if drift else 0


def cmd_uninstall_apply(args: argparse.Namespace) -> int:
    """Remove/revert every recorded artifact. See module docstring."""
    data = load_ledger()
    actions: list[dict] = []
    new_entries: list[dict] = []
    skipped_drift: list[str] = []

    for e in data["entries"]:
        kind = e.get("kind")
        path = Path(e.get("path", ""))
        if kind == "created":
            if not path.exists():
                actions.append({"path": e["path"], "action": "skip",
                                "reason": "already gone"})
                continue  # drop stale entry
            match = bool(e.get("sha256")) and sha256_of(path) == e["sha256"]
            if match:
                actions.append({"path": e["path"], "action": "delete",
                                "reason": f"created by {e.get('source', '?')}"})
                if not args.dry_run:
                    path.unlink()
                continue  # drop entry
            actions.append({"path": e["path"], "action": "skip-drift",
                            "reason": "content changed since install "
                                      "- inspect manually"})
            skipped_drift.append(e["path"])
            new_entries.append(e)  # keep, awaiting manual resolution
        elif kind == "modified":
            rev = e.get("revert", {})
            if not path.exists():
                actions.append({"path": e["path"], "action": "skip",
                                "reason": "file gone (nothing to revert)"})
                continue
            if rev.get("method") == "remove_marker_block":
                if args.dry_run:
                    begin = rev.get("begin", "")
                    changed = bool(begin) and begin in _read_text(path)
                else:
                    changed = strip_marker_block(path, rev.get("begin", ""),
                                                 rev.get("end", ""))
                actions.append({"path": e["path"],
                                "action": "revert" if changed else "noop",
                                "reason": "remove marker block" if changed
                                          else "marker absent (already reverted)"})
                continue  # entry resolved either way
            actions.append({"path": e["path"], "action": "keep",
                            "reason": f"unknown revert method: "
                                      f"{rev.get('method')}"})
            new_entries.append(e)
        else:
            new_entries.append(e)

    # Fallback scan: recognize Vise-generated wrappers even when the ledger
    # is lost (requires the Auto-generated header convention). Paths already
    # handled above are excluded (avoids double-reporting in --dry-run, where
    # nothing was actually deleted); drift-skipped files are protected - the
    # skip policy wins over the scan.
    handled = {a["path"] for a in actions}
    protected = set(skipped_drift)
    for bin_dir in args.fallback_bin:
        bdir = Path(os.path.expanduser(bin_dir))
        if not bdir.is_dir():
            continue
        for f in sorted(bdir.iterdir()):
            if not f.is_file() or f.stat().st_size > MAX_FALLBACK_SCAN_BYTES:
                continue
            if str(f) in protected or str(f) in handled:
                continue
            try:
                text = _read_text(f)
            except OSError:
                continue
            if str(VISE_ROOT) in text and AUTOGEN_MARK in text:
                actions.append({"path": str(f), "action": "delete",
                                "reason": "fallback scan: Vise-generated wrapper"})
                if not args.dry_run:
                    f.unlink()

    changed = bool(actions) or data["entries"] != new_entries
    if not args.dry_run and changed:
        data["entries"] = new_entries
        save_ledger(data)

    if args.json:
        print(json.dumps({"dry_run": args.dry_run, "actions": actions,
                          "skipped_drift": skipped_drift}, indent=2))
    else:
        prefix = "[dry-run] " if args.dry_run else ""
        if not actions:
            print(f"{prefix}manifest: nothing recorded outside VISE_ROOT "
                  "- nothing to clean")
        for a in actions:
            sym = {"delete": "delete ", "revert": "revert ", "skip": "skip   ",
                   "skip-drift": "SKIP!  ", "noop": "noop   ",
                   "keep": "keep   "}.get(a["action"], "       ")
            print(f"{prefix}{sym} {a['path']}  ({a['reason']})")
        if actions:
            counts: dict[str, int] = {}
            for a in actions:
                counts[a["action"]] = counts.get(a["action"], 0) + 1
            summary = ", ".join(f"{v} {k}" for k, v in sorted(counts.items()))
            print(f"{prefix}manifest summary: {summary}")

    return 3 if skipped_drift else 0


def cmd_path(_args: argparse.Namespace) -> int:
    print(LEDGER_PATH)
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="manifest.py",
        description="Ledger of artifacts Vise places outside VISE_ROOT.")
    sub = parser.add_subparsers(dest="command", required=True)

    p_add = sub.add_parser("add", help="record an artifact (upsert)")
    p_add.add_argument("kind", choices=["created", "modified"])
    p_add.add_argument("--path", required=True)
    p_add.add_argument("--source", required=True,
                       help="who wrote it, e.g. adapters/githubToolkit/thread")
    p_add.add_argument("--sha256", default=None,
                       help="created: override checksum (default: computed)")
    p_add.add_argument("--begin", default=None,
                       help="modified: revert block begin marker")
    p_add.add_argument("--end", default=None,
                       help="modified: revert block end marker")
    p_add.add_argument("--json", action="store_true")

    p_rm = sub.add_parser("remove", help="drop ledger entries for a path")
    p_rm.add_argument("--path", required=True)
    p_rm.add_argument("--kind", choices=["created", "modified"], default=None)
    p_rm.add_argument("--json", action="store_true")

    p_ls = sub.add_parser("list", help="list recorded artifacts")
    p_ls.add_argument("--json", action="store_true")

    p_ver = sub.add_parser("verify", help="check recorded artifacts are intact")
    p_ver.add_argument("--json", action="store_true")

    p_un = sub.add_parser("uninstall-apply",
                          help="remove/revert all recorded artifacts")
    p_un.add_argument("--dry-run", action="store_true")
    p_un.add_argument("--fallback-bin", action="append",
                      default=[str(Path.home() / ".local" / "bin")],
                      help="dir to scan for Vise-generated wrappers "
                           "(repeatable; default ~/.local/bin)")
    p_un.add_argument("--json", action="store_true")

    sub.add_parser("path", help="print the ledger file path")

    args = parser.parse_args(argv)
    return {"add": cmd_add, "remove": cmd_remove, "list": cmd_list,
            "verify": cmd_verify, "uninstall-apply": cmd_uninstall_apply,
            "path": cmd_path}[args.command](args)


if __name__ == "__main__":
    sys.exit(main())
