#!/usr/bin/env python3
"""register_adapters - generate registry.json by scanning adapters/.

The registry is a GENERATED machine-local artifact (P2-1): it is NOT
repo-managed and is (re)created by the init flow. setup.sh
invokes this script automatically; run it manually after adding/removing
an adapter:

    python3 init/register_adapters.py

Scans:  adapters/*/vise.adapter.json
Writes: .vise/registry.json (overwritten every run)
        .vise/requirements.txt (aggregated from each adapter's python_deps)

An adapter can opt out via "enabled": false in its vise.adapter.json.
"""
from __future__ import annotations

import json
import re
import sys
from datetime import datetime, timezone
from pathlib import Path

VISE_ROOT = Path(__file__).resolve().parent.parent
ADAPTERS_DIR = VISE_ROOT / "adapters"
REGISTRY_PATH = VISE_ROOT / ".vise" / "registry.json"
REQUIREMENTS_PATH = VISE_ROOT / ".vise" / "requirements.txt"


def scan_adapters() -> tuple[list[dict], list[str]]:
    """Scan adapters/*/vise.adapter.json. Returns (adapters, warnings)."""
    adapters: list[dict] = []
    warnings: list[str] = []
    if not ADAPTERS_DIR.is_dir():
        return adapters, [f"adapters directory not found: {ADAPTERS_DIR}"]

    for manifest_path in sorted(ADAPTERS_DIR.glob("*/vise.adapter.json")):
        rel_dir = manifest_path.parent.relative_to(VISE_ROOT).as_posix()
        try:
            manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError) as exc:
            warnings.append(f"skip {rel_dir}: cannot parse manifest ({exc})")
            continue
        adapter_id = manifest.get("adapter_id")
        if not adapter_id:
            warnings.append(f"skip {rel_dir}: manifest has no adapter_id")
            continue
        adapters.append({
            "adapter_id": adapter_id,
            "path": rel_dir,
            "enabled": bool(manifest.get("enabled", True)),
        })

    # Enforce unique adapter_id (first wins)
    seen: set[str] = set()
    unique: list[dict] = []
    for a in adapters:
        if a["adapter_id"] in seen:
            warnings.append(
                f"skip duplicate adapter_id '{a['adapter_id']}' at {a['path']}")
            continue
        seen.add(a["adapter_id"])
        unique.append(a)

    unique.sort(key=lambda a: a["adapter_id"])
    return unique, warnings


_REQ_NAME_RE = re.compile(r"^([A-Za-z0-9][A-Za-z0-9._-]*)")
_REQ_VER_RE = re.compile(r"(\d+(?:\.\d+)*)")


def _normalize(name: str) -> str:
    """Normalize a package name per PEP 503 (lowercase, collapse -_. to -)."""
    return re.sub(r"[-_.]+", "-", name).lower()


def _min_version(req: str) -> tuple[int, ...]:
    """First numeric version in a requirement spec, e.g. 'requests>=2.31' -> (2, 31)."""
    m = _REQ_VER_RE.search(req)
    if not m:
        return ()
    return tuple(int(part) for part in m.group(1).split("."))


def collect_python_deps(adapters: list[dict]) -> list[str]:
    """Aggregate python_deps declared by enabled adapters into a requirements list.

    Dedupe by normalized package name; on collision keep the requirement with
    the highest lower-bound version. Result is sorted for determinism.
    """
    chosen: dict[str, str] = {}
    for a in adapters:
        if not a["enabled"]:
            continue
        manifest_path = (VISE_ROOT / a["path"] / "vise.adapter.json")
        try:
            manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError):
            continue
        for req in manifest.get("python_deps", []):
            if not isinstance(req, str) or not req.strip():
                continue
            req = req.strip()
            m = _REQ_NAME_RE.match(req)
            if not m:
                continue
            key = _normalize(m.group(1))
            if key not in chosen or _min_version(req) > _min_version(chosen[key]):
                chosen[key] = req
    return sorted(chosen.values(), key=lambda r: _normalize(r))


def write_requirements(packages: list[str]) -> None:
    """Write the generated requirements.txt (machine-local, not repo-managed)."""
    lines = [
        "# AUTO-GENERATED by init/register_adapters.py — do not edit, not repo-managed.",
        "# Regenerated on every `bash init/setup.sh` from adapters' `python_deps`.",
    ]
    if packages:
        lines.extend(packages)
    else:
        lines.append("# (no adapter declared third-party Python deps)")
    REQUIREMENTS_PATH.parent.mkdir(parents=True, exist_ok=True)
    REQUIREMENTS_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> int:
    adapters, warnings = scan_adapters()
    for w in warnings:
        print(f"register_adapters: WARNING: {w}", file=sys.stderr)

    registry = {
        "_doc": ("AUTO-GENERATED by init/register_adapters.py - do not edit, "
                 "not repo-managed. Regenerate after adding/removing adapters."),
        "version": 1,
        "generated_at": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "adapters": adapters,
    }
    REGISTRY_PATH.parent.mkdir(parents=True, exist_ok=True)
    REGISTRY_PATH.write_text(
        json.dumps(registry, indent=2) + "\n", encoding="utf-8")

    packages = collect_python_deps(adapters)
    write_requirements(packages)

    enabled = sum(1 for a in adapters if a["enabled"])
    print(f"register_adapters: wrote {REGISTRY_PATH.relative_to(VISE_ROOT)} "
          f"({enabled}/{len(adapters)} adapter(s) enabled)")
    print(f"register_adapters: wrote {REQUIREMENTS_PATH.relative_to(VISE_ROOT)} "
          f"({len(packages)} python package(s) required)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
