#!/usr/bin/env bash
# Vise one-line setup (Git Bash / Linux / macOS).
# 1. Detect installed tools (Python >= 3.11, Git, 7-Zip, VS Code)
# 2. Create/refresh the project virtual environment (.venv)
# 3. (Re)generate .vise/tool_paths.json (python -> .venv) + .vise/python
# 4. (Re)generate .vise/registry.json + .vise/requirements.txt by scanning
#    adapters/ (generated artifacts, not repo-managed)
# 5. Capture the adapter baseline (C13; only when absent - see core/baseline.py)
# 6. Install adapter Python dependencies into .venv
# 7. Update shell startup to auto-load Vise commands
# 8. Run viseinit to initialize all Vise configurations
# Every step is idempotent: re-running only refreshes machine-local state.
set -euo pipefail

VISE_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
VAR_DIR="$VISE_ROOT/.vise"
mkdir -p "$VAR_DIR"
COTS_FILE="$VAR_DIR/tool_paths.json"

echo "== Vise setup =="
echo "VISE_ROOT: $VISE_ROOT"

# --- 1. Detect tools -------------------------------------------------------
find_python() {
    local candidates=(python3 python3.13 python3.12 python3.11 \
        "$HOME/miniconda3/bin/python3" /opt/conda/bin/python3)
    for c in "${candidates[@]}"; do
        local path
        if [[ "$c" == */* ]]; then
            [[ -x "$c" ]] && path="$c" || continue
        else
            path="$(command -v "$c" 2>/dev/null)" || continue
        fi
        if "$path" -c 'import sys; sys.exit(0 if sys.version_info >= (3, 11) else 1)' 2>/dev/null; then
            echo "$path"; return 0
        fi
    done
    return 1
}

detect() {  # first match wins, empty string otherwise
    for c in "$@"; do
        command -v "$c" 2>/dev/null && return 0
    done
    echo ""
}

PYTHON_BIN="$(find_python || true)"
GIT_BIN="$(detect git)"
SEVENZIP_BIN="$(detect 7z 7zz)"
VSCODE_BIN="$(detect code)"

[[ -n "$PYTHON_BIN" ]] || { echo "ERROR: Python >= 3.11 not found." >&2; exit 1; }
[[ -n "$GIT_BIN" ]]    || { echo "ERROR: Git not found." >&2; exit 1; }

# --- 2. Create/refresh the project virtual environment (.venv) -------------
VENV_DIR="$VISE_ROOT/.venv"
venv_python() {  # print the .venv interpreter if it exists (Unix or Git Bash)
    if [[ -x "$VENV_DIR/bin/python" ]]; then
        echo "$VENV_DIR/bin/python"
    elif [[ -x "$VENV_DIR/Scripts/python.exe" ]]; then
        echo "$VENV_DIR/Scripts/python.exe"
    fi
}
echo
echo "== Virtual environment (.venv) =="
if [[ -z "$(venv_python)" ]]; then
    "$PYTHON_BIN" -m venv "$VENV_DIR"
    echo "Created $VENV_DIR (from $PYTHON_BIN)"
else
    echo "Reusing existing $VENV_DIR"
fi
VENV_PYTHON="$(venv_python)"
[[ -n "$VENV_PYTHON" ]] || { echo "ERROR: failed to create .venv interpreter." >&2; exit 1; }

# --- 3. (Re)generate tool_paths.json (python -> .venv interpreter) ---------
json_or_null() { [[ -n "$1" ]] && printf '"%s"' "$1" || printf 'null'; }
{
    printf '{\n'
    printf '  "_doc": "AUTO-GENERATED by init/setup.sh — do not edit. Will be overwritten on next setup.",\n'
    printf '  "python": %s,\n'     "$(json_or_null "$VENV_PYTHON")"
    printf '  "git": %s,\n'        "$(json_or_null "$GIT_BIN")"
    printf '  "7zip": %s,\n'       "$(json_or_null "$SEVENZIP_BIN")"
    printf '  "vscode": %s,\n'     "$(json_or_null "$VSCODE_BIN")"
    printf '  "detected_at": "%s",\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)"
    printf '  "os": "%s"\n' "$(uname -s | tr '[:upper:]' '[:lower:]')"
    printf '}\n'
} > "$COTS_FILE"
echo "Wrote $COTS_FILE:"
cat "$COTS_FILE"

# Record the interpreter for Vise shell functions (.venv interpreter)
echo "$VENV_PYTHON" > "$VAR_DIR/python"

# --- 4. (Re)generate .vise/registry.json + .vise/requirements.txt ----------
echo
echo "== Generating adapter registry + requirements =="
"$VENV_PYTHON" "$VISE_ROOT/init/register_adapters.py"

# --- 5. Capture adapter baselines (C13) -------------------------------------
# The baseline is the pristine reference an adapter is compared against, and
# what a zip/tarball install restores from when there is no repository.
# It is captured only when absent: re-running setup after an adapter was
# edited must never bless that edit as "original". Accepting new state as the
# reference is an explicit act: visectl adapter rebaseline <id>.
echo
echo "== Capturing adapter baselines =="
"$VENV_PYTHON" "$VISE_ROOT/core/baseline.py" establish --all \
    || echo "WARNING: baseline capture failed; 'visectl adapter status' will report unbaselined" >&2

# --- 6. Install adapter Python dependencies into .venv ---------------------
REQ_FILE="$VISE_ROOT/.vise/requirements.txt"
echo
echo "== Installing Python dependencies (.venv) =="
if [[ -f "$REQ_FILE" ]] && grep -qE '^[^#[:space:]]' "$REQ_FILE"; then
    if [[ -n "${PIP_INDEX_URL:-}" ]]; then
        # Respect an explicit index already configured in the environment
        echo "Using PIP_INDEX_URL from environment: $PIP_INDEX_URL"
        "$VENV_PYTHON" -m pip install -r "$REQ_FILE"
    else
        echo "Probing package indexes (official + mirrors) for the fastest..."
        INDEX_URL="$("$VENV_PYTHON" "$VISE_ROOT/init/pick_pip_index.py" || true)"
        if [[ -n "$INDEX_URL" ]]; then
            echo "Fastest index: $INDEX_URL"
            "$VENV_PYTHON" -m pip install -r "$REQ_FILE" --index-url "$INDEX_URL"
        else
            echo "No mirror reachable; using pip's default index."
            "$VENV_PYTHON" -m pip install -r "$REQ_FILE"
        fi
    fi
else
    echo "No third-party Python dependencies declared by adapters; skipping pip."
fi

# --- 7. Update shell startup to auto-load Vise commands --------------------
detect_rc() {
    local shell_name
    shell_name="$(basename "${SHELL:-bash}")"
    case "$shell_name" in
        zsh)  echo "$HOME/.zshrc" ;;
        *)    echo "$HOME/.bashrc" ;;  # bash or fallback
    esac
}

RC_FILE="$(detect_rc)"
MARKER="# >>> Vise >>>"
MARKER_END="# <<< Vise <<<"
BLOCK="$MARKER
[[ -f \"$VISE_ROOT/core/vise_functions.sh\" ]] && source \"$VISE_ROOT/core/vise_functions.sh\"
$MARKER_END"
touch "$RC_FILE"
if grep -qF "$MARKER" "$RC_FILE"; then
    echo "Shell startup already contains Vise block ($RC_FILE), skipped."
else
    mkdir -p "$(dirname "$RC_FILE")"
    printf '\n%s\n' "$BLOCK" >> "$RC_FILE"
    echo "Added Vise loader to $RC_FILE"
fi

# Record the rc modification in the uninstall ledger (idempotent upsert).
# Best-effort: a failed record only means uninstall falls back to the
# marker-based rc cleanup, which is why it must not abort the setup.
"$VENV_PYTHON" "$VISE_ROOT/core/manifest.py" add modified \
    --path "$RC_FILE" --source "init/setup.sh" \
    --begin "$MARKER" --end "$MARKER_END" \
    || echo "WARNING: could not record rc block in manifest ledger" >&2

# --- 8. Run viseinit ---------------------------------------------------------
echo
echo "== Running viseinit --all =="
"$VENV_PYTHON" "$VISE_ROOT/core/viseinit.py" --all

echo
echo "One-line setup complete! Open a new shell (or: source $RC_FILE),"
echo "then try: viseinit --all"
echo "Or use:  visectl list"
echo "Already-open shells pick up adapter/shell changes on your next vise"
echo "command (trigger-based reload); to force it now: visereload"
echo "To uninstall: bash init/uninstall.sh"
